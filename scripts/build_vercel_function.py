def module(name):
    s = open(os.path.join(PKG, name + ".py"), encoding="utf-8").read()
    s = re.sub(r"^from \.[^\n]*\n", "", s, flags=re.M)                       # the modules are inlined
    s = re.sub(r'\nif __name__ == "__main__":\n    main\(\)\n?', "\n", s)
    return f"\n\n# {'=' * 30} fastelo/{name}.py {'=' * 30}\n" + s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--repo", default="irsotarriva/fastelo")
    ap.add_argument("--revision", default=None, help="commit of the model repo (default: its current head)")
    args = ap.parse_args()
    revision = args.revision
    if revision is None:
        from huggingface_hub import HfApi
        revision = HfApi().model_info(args.repo).sha
    import subprocess
    commit = subprocess.run(["git", "-C", HERE, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    src = (HEADER.format(commit=commit or "?", repo=args.repo)
           + module("vocab") + module("response") + "\napply_response = apply\n"
           + module("likelihood") + "\nRATING_GRID, likelihood_curve = GRID, curve\n" + module("lite")
           + HANDLER.format(repo=args.repo, revision=revision))
    compile(src, args.out, "exec")
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    print(f"wrote {args.out} ({len(src) / 1e3:.0f} kB), models {args.repo}@{revision[:12]}")


if __name__ == "__main__":
    main()
